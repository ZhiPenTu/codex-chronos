#!/usr/bin/env python3
"""Embed the management UI and egress helper in the native plugin."""
import hashlib
from pathlib import Path
root=Path(__file__).resolve().parent
raw=(root/'dashboard.html').read_bytes()
numbers=[str(n) for n in raw]
bundle = ('/* Auto-generated by embed_ui.py; do not edit. */\n'
    'static const unsigned char dashboard_html[] = {\n' +
    '\n'.join('  '+', '.join(numbers[i:i+20])+',' for i in range(0,len(numbers),20)) +
    '\n};\nstatic const size_t dashboard_html_size = sizeof(dashboard_html);\n')

raw = (root / 'refresh_egress.py').read_bytes()
numbers = [str(n) for n in raw]
digest = hashlib.sha256(raw).hexdigest()
bundle += (
        'static const unsigned char refresh_helper[] = {\n' +
        '\n'.join('  ' + ', '.join(numbers[i:i+20]) + ',' for i in range(0, len(numbers), 20)) +
        '\n};\nstatic const char refresh_helper_name[] = "refresh_egress-' + digest + '.py";\n')

(root / 'dashboard_bundle.h').write_text(bundle, encoding='ascii')
